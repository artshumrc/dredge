// Generate src/unicode61.ts from SQLite itself: every code point is run through
// FTS5's `unicode61 remove_diacritics 2` tokenizer between two letters, and the
// tokens that come back say whether it separates, survives, folds or vanishes.
// Run with `node scripts/build-unicode61.mjs` after a SQLite upgrade.

import { writeFile } from "node:fs/promises";
import { DatabaseSync } from "node:sqlite";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const out = resolve(dirname(fileURLToPath(import.meta.url)), "..", "src", "unicode61.ts");
const isSurrogate = (cp) => cp >= 0xd800 && cp <= 0xdfff;

const db = new DatabaseSync(":memory:");
db.exec("CREATE VIRTUAL TABLE t USING fts5(x, tokenize='unicode61 remove_diacritics 2')");
const insert = db.prepare("INSERT INTO t(rowid, x) VALUES (?, ?)");
db.exec("BEGIN");
for (let cp = 0; cp <= 0x10ffff; cp += 1) {
  if (!isSurrogate(cp)) {
    insert.run(cp + 1, `a${String.fromCodePoint(cp)}b`);
  }
}
db.exec("COMMIT");
db.exec("CREATE VIRTUAL TABLE v USING fts5vocab(t, 'instance')");

const tokens = new Map();
for (const row of db.prepare("SELECT term, doc FROM v ORDER BY doc, offset").iterate()) {
  const cp = Number(row.doc) - 1;
  tokens.set(cp, [...(tokens.get(cp) ?? []), row.term]);
}

const separators = [];
const folds = [];
for (let cp = 0; cp <= 0x10ffff; cp += 1) {
  if (isSurrogate(cp)) {
    continue;
  }
  const found = tokens.get(cp) ?? [];
  if (found.length === 2) {
    separators.push(cp);
    continue;
  }
  const folded = found[0].slice(1, -1);
  if (folded !== String.fromCodePoint(cp)) {
    folds.push([cp, folded === "" ? 0 : folded.codePointAt(0)]);
  }
}

const ranges = [];
for (const cp of separators) {
  const last = ranges.at(-1);
  if (last && last[1] === cp - 1) {
    last[1] = cp;
  } else {
    ranges.push([cp, cp]);
  }
}

const runs = [];
for (const [cp, to] of folds) {
  const delta = to === 0 ? 0 : to - cp;
  const last = runs.at(-1);
  if (last && last.delta === delta) {
    const stride = cp - last.end;
    if ((last.count === 1 && stride <= 2) || (last.count > 1 && stride === last.stride)) {
      last.stride = stride;
      last.count += 1;
      last.end = cp;
      continue;
    }
  }
  runs.push({ start: cp, count: 1, stride: 1, delta, end: cp });
}

let previous = 0;
const separatorData = ranges.flatMap(([start, end]) => {
  const pair = [start - previous, end - start];
  previous = end;
  return pair;
});
previous = 0;
const foldData = runs.flatMap((run) => {
  const entry = [run.start - previous, run.count, run.stride, run.delta];
  previous = run.start;
  return entry;
});

const wrap = (values) =>
  values
    .join(",")
    .replace(/((?:[^,]*,){24})/g, "$1\n  ")
    .trimEnd();

await writeFile(
  out,
  `// Generated by scripts/build-unicode61.mjs from SQLite ${String(
    db.prepare("SELECT sqlite_version() AS v").get().v,
  )}. Do not edit.

// Separator ranges as [gap from the previous range's end, length - 1] pairs.
export const SEPARATORS = [
  ${wrap(separatorData)},
];

// Fold runs as [gap from the previous run's start, count, stride, delta]
// quadruples; a delta of 0 removes the code point from its token.
export const FOLDS = [
  ${wrap(foldData)},
];
`,
);
console.log(`${ranges.length} separator ranges, ${runs.length} fold runs -> ${out}`);
